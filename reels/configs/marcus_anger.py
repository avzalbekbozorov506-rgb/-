import numpy as np
from PIL import Image, ImageFilter
from scipy import ndimage as ndi

def dark_studio(im):
    """Бюст снят на светлом сером фоне (100→230, с тенью) — уводим фон в тёмную «студию».
    Фон: серый (насыщенность ≤ 10), гладкий (бронза фактурная), связан с краем кадра. Старая версия (порог яркости > 150)
    оставляла верх фона серым и давала пятно — заменена."""
    a = np.asarray(im).astype(np.float32); h, w, _ = a.shape
    lum = a.mean(2); sat = a.max(2) - a.min(2)
    sd = np.sqrt(np.maximum(ndi.uniform_filter(lum ** 2, 9) - ndi.uniform_filter(lum, 9) ** 2, 0))
    bg = ndi.binary_opening((sat <= 10) & (lum > 88) & (sd < 6), iterations=2)
    lab, _ = ndi.label(bg); edge = np.unique(np.concatenate([lab[0], lab[-1], lab[:, 0], lab[:, -1]])); edge = edge[edge > 0]
    fg = ndi.binary_fill_holes(ndi.binary_closing(~np.isin(lab, edge), iterations=4))
    fg = ndi.binary_erosion(fg, iterations=5)                             # срезаем светлую кайму по контуру
    m = np.asarray(Image.fromarray((fg * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(3))).astype(np.float32)[..., None] / 255
    yy = np.linspace(0, 1, h)[:, None, None]; xx = np.linspace(-1, 1, w)[None, :, None]
    dark = np.array([30, 24, 20], np.float32) * (1 - 0.45 * yy) * (1 - 0.35 * xx ** 2)   # тёплый тёмный фон с лёгкой виньеткой
    return Image.fromarray(np.clip(a * m + dark * (1 - m), 0, 255).astype(np.uint8))
