def dark_studio(im):
    """Бюст снят на светлом фоне — уводим фон в тёмный, чтобы кадр не выбивался из стиля."""
    a = np.asarray(im).astype(np.float32); lum = a.mean(2); sat = a.max(2) - a.min(2)
    m = ((lum > 150) & (sat < 40)).astype(np.float32)
    m = np.asarray(Image.fromarray((m * 255).astype(np.uint8)).filter(ImageFilter.GaussianBlur(12))).astype(np.float32)[..., None] / 255
    return Image.fromarray((a * (1 - m) + np.array([22, 18, 16]) * m).astype(np.uint8))
