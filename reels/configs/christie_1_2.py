def route_card(lt, D):
    im = bg(); d = ImageDraw.Draw(im, "RGBA")
    k = ease(lt / 0.7)
    text_c(d, (W // 2, 620), "1922", sans("Black", 230), GOLD + (int(255 * k),))
    pts = [(220, 1000), (W // 2, 930), (860, 1000)]
    for i, (t, p) in enumerate((("Лондон", pts[0]), ("Южная Африка", pts[1]), ("Гавайи", pts[2]))):
        kk = ease((lt - 0.8 - i * 0.7) / 0.5)
        d.ellipse((p[0] - 18, p[1] - 18, p[0] + 18, p[1] + 18), fill=WHITE + (int(255 * kk),))
        text_c(d, (p[0], p[1] + 70), t, sans("Black", 40), WHITE + (int(255 * kk),))
    for a, b in zip(pts, pts[1:]):
        kk = ease((lt - 1.2) / 1.6)
        d.line((a[0] + 20, a[1], a[0] + 20 + (b[0] - a[0] - 40) * kk, a[1] + (b[1] - a[1]) * kk), fill=GOLD + (200,), width=6)
    return im

